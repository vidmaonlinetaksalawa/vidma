-- Logged-in students can read class information. Admins can manage it.
create policy subjects_select on public.subjects for select to authenticated using(true);
create policy subjects_insert on public.subjects for insert to authenticated with check(public.is_admin());
create policy subjects_update on public.subjects for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy subjects_delete on public.subjects for delete to authenticated using(public.is_admin());
-- Students can only read Free recordings or recordings explicitly assigned to them.
-- Admins can read all recordings. This is the security boundary; the UI filter alone is not enough.
create policy recordings_select on public.recordings for select to authenticated
using(
  public.is_admin()
  or is_free = true
  or exists (
    select 1 from public.recording_access ra
    where ra.recording_id = recordings.id
      and ra.student_id = auth.uid()
  )
);
create policy recordings_insert on public.recordings for insert to authenticated with check(public.is_admin());
create policy recordings_update on public.recordings for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy recordings_delete on public.recordings for delete to authenticated using(public.is_admin());
create policy recording_access_select on public.recording_access for select to authenticated using(student_id=auth.uid() or public.is_admin());
create policy recording_access_insert on public.recording_access for insert to authenticated with check(public.is_admin());
create policy recording_access_delete on public.recording_access for delete to authenticated using(public.is_admin());

