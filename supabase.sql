create table if not exists public.profiles(
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 dob date,
 grade int check(grade between 5 and 11),
 address text,
 school text,
 whatsapp text,
 phone text,
 avatar_url text,
 role text default 'student' check(role in('student','admin')),
 created_at timestamptz default now()
);
create table if not exists public.subjects(id bigint generated by default as identity primary key,name text not null,grade int check(grade between 5 and 11),created_at timestamptz default now());
create table if not exists public.recordings(id bigint generated by default as identity primary key,subject_id bigint references public.subjects(id) on delete cascade,subject_name text,grade int,month text,class_date date,title text,youtube_url text not null,created_at timestamptz default now());
alter table public.recordings add column if not exists is_free boolean not null default false;
create table if not exists public.recording_access(
 id bigint generated by default as identity primary key,
 student_id uuid not null references public.profiles(id) on delete cascade,
 recording_id bigint not null references public.recordings(id) on delete cascade,
 created_at timestamptz default now(),
 unique(student_id,recording_id)
);
create table if not exists public.timetable(id bigint generated by default as identity primary key,subject text,subject_name text,grade int,day text,time text,created_at timestamptz default now());
create table if not exists public.class_fees(id bigint generated by default as identity primary key,grade int,month text,amount numeric(10,2),note text,created_at timestamptz default now());
alter table public.class_fees add column if not exists note text;
-- Subject grade is optional. Existing grade values are kept for compatibility, but the admin form no longer asks for one.
alter table public.subjects alter column grade drop not null;

create table if not exists public.class_grades(
 grade int primary key
);
insert into public.class_grades(grade) values (5),(6),(7),(8),(9),(10),(11) on conflict do nothing;

create table if not exists public.class_months(
 id bigint generated by default as identity primary key,
 name text not null unique,
 created_at timestamptz default now()
);
insert into public.class_months(name) values
('January'),('February'),('March'),('April'),('May'),('June'),('July'),('August'),('September'),('October'),('November'),('December')
on conflict(name) do nothing;

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
begin
 insert into public.profiles(id,full_name,dob,grade,address,school,whatsapp,phone)
 values(new.id,new.raw_user_meta_data->>'full_name',nullif(new.raw_user_meta_data->>'dob','')::date,nullif(new.raw_user_meta_data->>'grade','')::int,new.raw_user_meta_data->>'address',new.raw_user_meta_data->>'school',new.raw_user_meta_data->>'whatsapp',new.raw_user_meta_data->>'phone');
 return new;
end;$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();

create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;


